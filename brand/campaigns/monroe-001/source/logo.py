"""Builds the tucker. logo as pure vector paths (no font needed to display it).
Letters: Sora (the site's display face) at weight 700. The period is the bear's nose,
drawn from the round-3 master's nose, in orange."""
import sys, io
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.boundsPen import BoundsPen

src, out = sys.argv[1], sys.argv[2]
font = instantiateVariableFont(TTFont(src), {"wght": 700})
upm = font["head"].unitsPerEm
cmap = font.getBestCmap(); gs = font.getGlyphSet(); hmtx = font["hmtx"]
ORANGE = "#EE6A24"
INK = "#101828"
# The bear's nose as seen on the round-3 master: a wide, softly rounded top that narrows to a
# rounded point. Drawn in a 100 x 78 box (y down).
NOSE = "M50 0C79 0 100 7 100 25C100 46 72 72 50 78C28 72 0 46 0 25C0 7 21 0 50 0Z"
NX, NY, NW, NH = 0, 0, 100, 78

def word(text, nose_gap=0.055, nose_w=0.235):
    x = 0; parts = []
    for ch in text:
        g = cmap[ord(ch)]
        pen = SVGPathPen(gs)
        gs[g].draw(pen)
        parts.append(f'<path transform="translate({x} 0)" d="{pen.getCommands()}"/>')
        x += hmtx[g][0]
    # period = nose, sitting on the baseline
    w = nose_w * upm; s = w / NW; h = NH * s
    nx = x + nose_gap * upm
    nose = f'<path fill="{ORANGE}" transform="translate({nx} {h}) scale({s} {-s}) translate({-NX} {-NY})" d="{NOSE}"/>'
    width = nx + w
    return parts, nose, width

def svg(text, color, name, pad=0.06):
    parts, nose, width = word(text)
    asc = font["hhea"].ascent; desc = -font["hhea"].descent
    # tight vertical box from actual glyph bounds
    bp = BoundsPen(gs)
    x = 0
    ymin, ymax = 0, 0
    for ch in text:
        g = cmap[ord(ch)]; b = BoundsPen(gs); gs[g].draw(b)
        if b.bounds: ymin = min(ymin, b.bounds[1]); ymax = max(ymax, b.bounds[3])
    p = pad * upm
    vb_h = ymax - ymin + 2 * p
    body = "\n  ".join(parts)
    doc = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="{-p:.0f} 0 {width + 2*p:.0f} {vb_h:.0f}" role="img" aria-label="tucker.">
  <title>tucker.</title>
  <!-- Generated by brand/campaigns/monroe-001/source/logo.py: Sora 700 outlines + the bear-nose period ({ORANGE}). -->
  <g transform="translate(0 {ymax + p:.0f}) scale(1 -1)">
  <g fill="{color}">
  {body}
  </g>
  {nose}
  </g>
</svg>
'''
    open(f"{out}/{name}", "w").write(doc)
    print(name, round(width), round(vb_h))

svg("tucker", INK, "tucker-wordmark.svg")
