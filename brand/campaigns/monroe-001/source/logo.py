# ---- Product: the same outlines for the website (src/components/logo-paths.ts) ----
def glyph_parts(text):
    x = 0; parts = []
    for ch in text:
        g = cmap[ord(ch)]; pen = SVGPathPen(gs); gs[g].draw(pen)
        parts.append((x, pen.getCommands())); x += hmtx[g][0]
    return parts, x

def ts_word(text):
    parts, adv = glyph_parts(text)
    ymin = min(BoundsPen_bounds(ch)[1] for ch in text); ymax = max(BoundsPen_bounds(ch)[3] for ch in text)
    w = 0.235 * upm; s = w / NW; h = NH * s; nx = adv + 0.055 * upm
    # Flip y here so the browser needs no transforms: y' = ymax - y.
    letters = "".join(f'<path transform="translate({px} {ymax}) scale(1 -1)" d="{d}"/>' for px, d in parts)
    nose = f'<path transform="translate({nx:.1f} {ymax - h:.1f}) scale({s:.4f})" d="{NOSE}"/>'
    return f"0 0 {nx + w:.0f} {ymax - ymin:.0f}", letters, nose, ymax

def BoundsPen_bounds(ch):
    b = BoundsPen(gs); gs[cmap[ord(ch)]].draw(b); return b.bounds

